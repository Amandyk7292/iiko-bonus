-- Editable customer guidance. No changes to loyalty configuration or calculations.
create table public.loyalty_faq (
  id uuid primary key default gen_random_uuid(),
  question_ru text not null check (length(btrim(question_ru)) between 1 and 240),
  answer_ru text not null check (length(btrim(answer_ru)) between 1 and 4000),
  question_kk text not null default '' check (length(question_kk) <= 240),
  answer_kk text not null default '' check (length(answer_kk) <= 4000),
  sort_order integer not null default 0 check (sort_order >= 0),
  is_active boolean not null default true,
  check ((length(btrim(question_kk)) > 0) = (length(btrim(answer_kk)) > 0))
);

create index loyalty_faq_public_order on public.loyalty_faq (sort_order, id) where is_active;
alter table public.loyalty_faq enable row level security;
revoke all on public.loyalty_faq from public, anon, authenticated;
grant select, insert, update on public.loyalty_faq to service_role;
create policy loyalty_faq_service_only on public.loyalty_faq
  for all to service_role using (true) with check (true);

comment on table public.loyalty_faq is
  'Plain-text RU/KK FAQ; backend public API exposes active questions only. Hide reversibly with is_active=false.';

